// The token radar's model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) plus every other pre-token protocol the snapshot ranks as rankable:
// 289 rows on this snapshot. A protocol is pre-token when its record carries no
// token (no market cap, no CoinGecko id, no symbol); live-token protocols are
// kept apart and shown at the market's own value, never mixed into the board.
//
// Implied value follows only from the snapshot's own figures. The one number
// the starter fixes by hand, the TVL multiple, is here read off the snapshot
// itself: for each category, the median market-cap-to-TVL ratio of the
// live-token protocols in that category (three or more of them, else the
// whole snapshot's median), clamped to [0.05, 0.80]. A DEX is therefore
// priced off live DEXs and a lender off live lenders, and no protocol name
// is ever special-cased: the same function scores every row.
//
//   multiple   = category median mcap / TVL among live tokens (clamped)
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.7 + min(age_days, 1095) / 1095 x 0.3   (age unknown: 365)
//   breadth    = 1 + 0.01 x min(chains, 10)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// The dashboard states this formula and prints the category table the run
// actually computed, and its Model tab lets a reader move the constants and
// watch the board re-rank in the browser.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

